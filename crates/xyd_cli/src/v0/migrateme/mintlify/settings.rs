        let mut cases: Vec<String> = fs::read_dir(&testdata)
            .unwrap()
            .flatten()
            .filter(|e| e.file_type().map(|t| t.is_dir()).unwrap_or(false))
            .map(|e| e.file_name().to_string_lossy().into_owned())
            .collect();
        cases.sort();
        assert!(!cases.is_empty(), "no migrateme mintlify fixtures found");

