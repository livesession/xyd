mod service;

use serde_json::{Map, Value};
use std::collections::BTreeMap;

use naming::{crate_name, screaming_snake_case};

const HEADER: &str = "Code generated by opensdk. DO NOT EDIT.";

/// Prepend the ownership header for `.rs` files (as `// ...`), exactly once.
/// `.toml` (Cargo.toml) gets no header — matching the orchestrator's
/// extension table.
fn with_header(rel_path: &str, content: String) -> String {
    if !rel_path.ends_with(".rs") {
        return content;
    }
    let rendered = format!("// {HEADER}");
    if content.starts_with(&rendered) {
        content
    } else {
        format!("{rendered}\n\n{content}")
    }
}

/// The Cargo package / lib crate name (packageName ?? moduleName ?? crateName).
fn resolve_crate(spec: &Value) -> String {
    // Options are folded into the IR call in the JS; the Rust entry takes only
    // the spec (the emitter tests pass no options), so use the defaults.
    let title = spec
        .get("info")
        .and_then(|i| i.get("title"))
        .and_then(|t| t.as_str())
        .unwrap_or("");
    crate_name(title)
}

fn resolve_env_var(spec: &Value, crate_: &str) -> String {
    spec.get("security")
        .and_then(|s| s.as_array())
        .and_then(|arr| {
            arr.iter().find_map(|s| {
                s.get("envVar")
                    .and_then(|e| e.as_str())
                    .filter(|e| !e.is_empty())
            })
        })
        .map(|e| e.to_string())
        .unwrap_or_else(|| format!("{}_API_KEY", screaming_snake_case(crate_)))
}

/// Generate the SUBSTANTIVE Rust SDK files from an OpenSDK IR document.
/// Returns `{ relativePath: contents }` for the emitted (generated-code) files.
pub fn generate_rust(spec: &Value) -> BTreeMap<String, String> {
    let crate_ = resolve_crate(spec);
    let edition = "2021";
    let env_var = resolve_env_var(spec, &crate_);

    // Symbol table for the resource emitter (name → NamedType).
    let mut types: Map<String, Value> = Map::new();
    if let Some(arr) = spec.get("types").and_then(|t| t.as_array()) {
        for t in arr {
            if let Some(name) = t.get("name").and_then(|n| n.as_str()) {
                types.insert(name.to_string(), t.clone());
            }
        }
    }

    let mut files: BTreeMap<String, String> = BTreeMap::new();
    let mut put = |path: &str, content: String| {
        files.insert(path.to_string(), with_header(path, content));
    };

    // generateProject
    put(
        "Cargo.toml",
        project::render_cargo_toml(spec, &crate_, edition),
    );
    put("src/lib.rs", project::render_lib_rs(spec));
    // generateClient
    put("src/client.rs", client::render_client_file(spec, &env_var));
    // generateTypes
    put("src/models.rs", model::render_models_file(spec));
    // generateResources
    let ctx = service::RustCtx { types: &types };
    if let Some(resources) = spec.get("resources").and_then(|r| r.as_array()) {
        for resource in resources {
            let (path, content) = service::render_service_file(resource, &ctx);
            files.insert(path.clone(), with_header(&path, content));
        }
    }

    files
}
