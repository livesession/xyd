//! Rust SDK emitter — OpenSDK IR → generated Rust SDK code (Rust port of
//! `@xyd-js/opensdk-rust`, S6+ W7). Ports the SUBSTANTIVE generated-code
//! capabilities (generateProject/Client/Types/Resources) + the framework
//! orchestrator's header-prepend + capability order.
//!
//! DEFERRED (JS stays authoritative): the vendored runtime (src/transport.rs,
//! src/error.rs — fixed constants + a little sdk-behavior interpolation) and
//! the generated `tests/**` suite, plus napi + the JS shim. `generate_rust`
//! returns ONLY the files it emits (Cargo.toml, src/lib.rs, src/client.rs,
//! src/models.rs, src/<resource>.rs); the tier-1 test byte-compares per file.

mod client;
mod model;
mod naming;
mod plan;
