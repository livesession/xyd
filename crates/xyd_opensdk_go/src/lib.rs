//! Go SDK emitter — OpenSDK IR → buildable Go SDK (Rust port of
//! @xyd-js/opensdk-go), W7 chunk 4. Operates on serde_json::Value for the IR.
//!
//! COVERAGE (this chunk): the GENERATED-code path — the framework driver
//! (header + capability order) + go.mod + client.go + types.go +
//! <resource>.go, byte-identical to the goldens. The vendored fixed runtime
//! (option/, internal/requestconfig/, packages/{apijson,pagination,param},
//! testutil) and the SDK's own generated test files are NOT yet ported — see
//! the crate-level report. `generate_go` returns only the files it emits; a
//! caller/JS still supplies the runtime tree until that lands.

