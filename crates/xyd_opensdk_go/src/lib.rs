/// The engine ownership header prepended to every .go file.
const FILE_HEADER: &str = "// Code generated by opensdk. DO NOT EDIT.";

/// Minimal SdkBehavior defaults needed by the generated-code path
/// (methodInjectsIdempotency). The full defaults + spec.sdk deep-merge land
/// with the runtime port.
fn default_behavior() -> Value {
    serde_json::json!({
        "retry": { "maxRetries": 2 },
        "idempotency": { "headerName": "Idempotency-Key", "autoGenerateForPost": true },
    })
}

struct Options {
    pkg: String,
    module_path: String,
    go_version: String,
}

fn resolve_options(spec: &Value) -> Options {
    let title = spec
        .get("info")
        .and_then(|i| i.get("title"))
        .and_then(|t| t.as_str())
        .unwrap_or("");
    let pkg = go_package_name(title);
    let module_path = format!("github.com/example/{pkg}");
    Options {
        pkg,
        module_path,
        go_version: "1.22".to_string(),
    }
}

/// Prepend the .go ownership header (only for .go files), once.
fn with_header(rel: &str, content: String) -> String {
    if !rel.ends_with(".go") {
        return content;
    }
    if content.starts_with(FILE_HEADER) {
        return content;
    }
    format!("{FILE_HEADER}\n\n{content}")
}

/// Emit the GENERATED-code Go files (go.mod, client.go, types.go, per-resource
/// service files). Returns a sorted path→content map. NOTE: the vendored
/// runtime + generated tests are not included yet (see the module header).
pub fn generate_go(spec: &Value) -> std::collections::BTreeMap<String, String> {
    let opts = resolve_options(spec);
    let empty_map = Map::new();
    let types = spec.get("types").and_then(|t| t.as_array());
    let mut type_map: Map<String, Value> = Map::new();
    if let Some(types) = types {
        for t in types {
            if let Some(name) = t.get("name").and_then(|n| n.as_str()) {
                type_map.insert(name.to_string(), t.clone());
            }
        }
    }
    let _ = &empty_map;

    let ctx = GoCtx {
        module_path: opts.module_path.clone(),
        pkg: opts.pkg.clone(),
        types: &type_map,
        behavior: spec_behavior(spec),
    };

    let mut files: std::collections::BTreeMap<String, String> = Default::default();

    // generateProject
    files.insert(
        "go.mod".to_string(),
        with_header(
            "go.mod",
            format!("module {}\n\ngo {}\n", opts.module_path, opts.go_version),
        ),
    );
    // generateClient
    files.insert(
        "client.go".to_string(),
        with_header("client.go", render_client_file(spec, &ctx)),
    );
    // generateTypes
    if !type_map.is_empty() || types.map(|t| !t.is_empty()).unwrap_or(false) {
        files.insert(
            "types.go".to_string(),
            with_header("types.go", render_types_file(spec, &opts.pkg)),
        );
    }
    // generateResources
    if let Some(resources) = spec.get("resources").and_then(|r| r.as_array()) {
        for r in resources {
            let (path, content) = render_service_file(r, &ctx);
            files.insert(path.clone(), with_header(&path, content));
        }
    }

    files
}

/// spec.sdk deep-merged over the (minimal) defaults — enough for the
/// generated-code path. Full merge lands with the runtime port.
fn spec_behavior(spec: &Value) -> Value {
    let mut b = default_behavior();
    if let Some(sdk) = spec.get("sdk") {
        deep_merge(&mut b, sdk);
    }
    b
}

fn deep_merge(target: &mut Value, source: &Value) {
    if let (Some(t), Some(s)) = (target.as_object_mut(), source.as_object()) {
        for (k, v) in s {
            match t.get_mut(k) {
                Some(tv) if tv.is_object() && v.is_object() => deep_merge(tv, v),
                _ => {
                    t.insert(k.clone(), v.clone());
                }
            }
        }
    }
}
