//! Rust-source string helpers — port of rslit.ts. Renders clap builder-method
//! chains with correct indentation (not an AST), plus the `Uses` import block
//! and the assembled-file helper.

/// 4-space Rust indentation.
fn pad(n: usize) -> String {
    "    ".repeat(n)
}

/// A double-quoted Rust string literal. JSON escaping is Rust-compatible for our
/// content — mirrors JS `JSON.stringify(s)`.
pub fn json_str(s: &str) -> String {
    serde_json::to_string(s).expect("string serializes")
}

/// A value renderer: `Lit` is a pre-rendered scalar; `Chain` is a builder chain.
pub enum RsVal {
    Lit(String),
    Chain {
        base: String,
        calls: Vec<(String, Vec<RsVal>)>,
    },
}

/// A pre-rendered scalar (identifier, number, expression).
pub fn lit(s: impl Into<String>) -> RsVal {
    RsVal::Lit(s.into())
}

/// A Rust double-quoted string literal (JSON-escaped).
pub fn rs_str(s: &str) -> RsVal {
    RsVal::Lit(json_str(s))
}

/// A builder-method chain: `base` inline, then one `.method(args)` per line at
/// `indent + 1`; a multiline argument goes on its own lines (rustfmt style).
pub fn chain(base: impl Into<String>, calls: Vec<(String, Vec<RsVal>)>) -> RsVal {
    RsVal::Chain {
        base: base.into(),
        calls,
    }
}

impl RsVal {
    pub fn render(&self, indent: usize) -> String {
        match self {
            RsVal::Lit(s) => s.clone(),
            RsVal::Chain { base, calls } => {
                let mut out = base.clone();
                for (method, args) in calls {
                    let rendered: Vec<String> = args.iter().map(|a| a.render(indent + 2)).collect();
                    if rendered.iter().any(|r| r.contains('\n')) {
                        let block = rendered
                            .iter()
                            .map(|r| format!("{}{},", pad(indent + 2), r))
                            .collect::<Vec<_>>()
                            .join("\n");
                        out.push_str(&format!(
                            "\n{}.{}(\n{}\n{})",
                            pad(indent + 1),
                            method,
                            block,
                            pad(indent + 1)
                        ));
                    } else {
                        out.push_str(&format!(
                            "\n{}.{}({})",
                            pad(indent + 1),
                            method,
                            rendered.join(", ")
                        ));
                    }
                }
                out
            }
        }
    }
}

/// Indent every non-empty line of `text` by `levels` indent units.
pub fn indent(text: &str, levels: usize) -> String {
    let p = pad(levels);
    text.split('\n')
        .map(|line| {
            if line.is_empty() {
                line.to_string()
            } else {
                format!("{p}{line}")
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// The ownership header stamped on every generator-owned file.
pub const GENERATED_HEADER: &str = "// Code generated by opencli2rust. DO NOT EDIT.";

/// Tracks the `use` items a generated file needs, rendered as one sorted block.
#[derive(Default)]
pub struct Uses {
    items: Vec<String>,
}

impl Uses {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn add(&mut self, uses: &[&str]) -> &mut Self {
        for u in uses {
            if !self.items.iter().any(|x| x == u) {
                self.items.push(u.to_string());
            }
        }
        self
    }

    pub fn size(&self) -> usize {
        self.items.len()
    }

    /// Groups: std first, external crates next, `crate::`/`super::`/`self::`
    /// last — blank-line separated; each group sorted.
    pub fn render(&self) -> String {
        if self.items.is_empty() {
            return String::new();
        }
        let mut std_g: Vec<&String> = self
            .items
            .iter()
            .filter(|u| u.starts_with("std::"))
            .collect();
        let mut local_g: Vec<&String> = self
            .items
            .iter()
            .filter(|u| {
                u.starts_with("crate::") || u.starts_with("super::") || u.starts_with("self::")
            })
            .collect();
        let mut ext_g: Vec<&String> = self
            .items
            .iter()
            .filter(|u| {
                !u.starts_with("std::")
                    && !u.starts_with("crate::")
                    && !u.starts_with("super::")
                    && !u.starts_with("self::")
            })
            .collect();
        std_g.sort();
        local_g.sort();
        ext_g.sort();

        [std_g, ext_g, local_g]
            .iter()
            .filter(|g| !g.is_empty())
            .map(|g| {
                g.iter()
                    .map(|u| format!("use {u};"))
                    .collect::<Vec<_>>()
                    .join("\n")
            })
            .collect::<Vec<_>>()
            .join("\n\n")
    }
}

/// Assemble a complete generated Rust file: header + uses + declarations.
pub fn rs_file(uses: &Uses, decls: &[String]) -> String {
    rs_file_with_header(uses, decls, GENERATED_HEADER)
}

pub fn rs_file_with_header(uses: &Uses, decls: &[String], header: &str) -> String {
    let mut parts: Vec<String> = Vec::new();
    if !header.is_empty() {
        parts.push(header.to_string());
    }
    if uses.size() > 0 {
        parts.push(uses.render());
    }
    parts.extend(decls.iter().cloned());
    format!("{}\n", parts.join("\n\n"))
}
