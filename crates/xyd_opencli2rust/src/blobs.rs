//! Static HTTP primitives shared by every command handler.

use percent_encoding::{utf8_percent_encode, AsciiSet, NON_ALPHANUMERIC};
use serde_json::Value;

/// Escape a value for use inside a URL path segment (strict RFC 3986 unreserved).
const PATH_SEGMENT: &AsciiSet = &NON_ALPHANUMERIC.remove(b'-').remove(b'_').remove(b'.').remove(b'~');

pub fn path_escape(value: &str) -> String {
    utf8_percent_encode(value, PATH_SEGMENT).to_string()
}

/// A generic API request assembled by a command handler.
pub struct Request {
    pub method: &'static str,
    pub path: String,
    pub query: Vec<(&'static str, String)>,
    pub headers: Vec<(&'static str, String)>,
    pub body: Option<Vec<u8>>,
}

/// A request failure, inspectable from `CliOverrides::recover_error` / `print_error`.
#[derive(Debug)]
pub enum Error {
    /// The server answered with a 4xx/5xx status; `body` is the decoded response.
    Http { status: u16, body: Value },
    /// The request could not be sent or the response could not be read.
    Transport(String),
    /// A handler-side failure (flag decoding, body assembly, custom command logic).
    Invalid(String),
}

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Error::Http { status, body } => write!(f, "request failed: {status}: {body}"),
            Error::Transport(message) => write!(f, "request error: {message}"),
            Error::Invalid(message) => write!(f, "{message}"),
        }
    }
}

impl std::error::Error for Error {}

/// Decode a response body: JSON when it parses, the raw text otherwise.
pub(crate) fn decode(bytes: &[u8]) -> Value {
    serde_json::from_slice(bytes).unwrap_or_else(|_| Value::String(String::from_utf8_lossy(bytes).into_owned()))
}
