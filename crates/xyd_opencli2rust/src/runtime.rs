/// One environment-based auth attach block, or None for an unrecognized kind.
fn auth_block(scheme: &Value) -> Option<String> {
    let env = scheme
        .get("envVar")
        .and_then(|v| v.as_str())
        .unwrap_or("API_KEY");
    let name = scheme.get("name").and_then(|v| v.as_str()).unwrap_or("");
    match scheme.get("kind").and_then(|k| k.as_str()) {
        Some("bearer") => Some(format!(
            "    if let Ok(v) = std::env::var({}) {{\n        if !v.is_empty() {{\n            rb = rb.bearer_auth(v);\n        }}\n    }}",
            json_str(env)
        )),
        Some("apiKey-header") => Some(format!(
            "    if let Ok(v) = std::env::var({}) {{\n        if !v.is_empty() {{\n            rb = rb.header({}, v);\n        }}\n    }}",
            json_str(env),
            json_str(name)
        )),
        Some("apiKey-query") => Some(format!(
            "    if let Ok(v) = std::env::var({}) {{\n        if !v.is_empty() {{\n            rb = rb.query(&[({}, v.as_str())]);\n        }}\n    }}",
            json_str(env),
            json_str(name)
        )),
        Some("apiKey-cookie") => Some(format!(
            "    if let Ok(v) = std::env::var({}) {{\n        if !v.is_empty() {{\n            rb = rb.header(\"Cookie\", format!(\"{{}}={{}}\", {}, v));\n        }}\n    }}",
            json_str(env),
            json_str(name)
        )),
        Some("basic") => Some(format!(
            "    let user = std::env::var({}).unwrap_or_default();\n    let pass = std::env::var({}).unwrap_or_default();\n    if !user.is_empty() || !pass.is_empty() {{\n        rb = rb.basic_auth(user, Some(pass));\n    }}",
            json_str(&format!("{env}_USERNAME")),
            json_str(&format!("{env}_PASSWORD"))
        )),
        _ => None,
    }
}

/// `src/gen/runtime/config.rs` — base URL + auth derived from the root x-openapi.
pub fn config_rs(spec: &Value, bin_name: &str, base_url: &str) -> String {
    let prefix = screaming_snake_case(bin_name);
    let empty: Vec<Value> = Vec::new();
    let security = spec
        .get("x-openapi")
        .and_then(|x| x.get("security"))
        .and_then(|s| s.as_array())
        .unwrap_or(&empty);
    let blocks: Vec<String> = security.iter().filter_map(auth_block).collect();

    let apply_auth = if !blocks.is_empty() {
        format!(
            "/// Attach credentials read from the environment to the request.\npub fn apply_auth(mut rb: reqwest::RequestBuilder) -> reqwest::RequestBuilder {{\n{}\n    rb\n}}",
            blocks.join("\n")
        )
    } else {
        "/// Attach credentials read from the environment to the request.\npub fn apply_auth(rb: reqwest::RequestBuilder) -> reqwest::RequestBuilder {\n    rb\n}".to_string()
    };

    format!(
        "{HEADER}\n\n//! Spec-derived configuration: the API base URL and environment-based auth.\n\nconst DEFAULT_BASE_URL: &str = {};\n\n/// The API base URL, overridable via `{prefix}_BASE_URL`.\npub fn base_url() -> String {{\n    match std::env::var({}) {{\n        Ok(v) if !v.is_empty() => v,\n        _ => DEFAULT_BASE_URL.to_string(),\n    }}\n}}\n\n{apply_auth}\n",
        json_str(base_url),
        json_str(&format!("{prefix}_BASE_URL"))
    )
}

/// `Cargo.toml` (skipIfExists) — the crate manifest.
pub fn cargo_toml(spec: &Value, crate_name: &str, bin_name: &str, edition: &str) -> String {
    let version = spec
        .get("info")
        .and_then(|i| i.get("version"))
        .and_then(|v| v.as_str())
        .unwrap_or("0.1.0");
    format!(
        "# Generated once by opencli2rust — yours to edit; regeneration never overwrites it.\n\n[package]\nname = {}\nversion = {}\nedition = {}\n\n[dependencies]\nclap = {{ version = \"4\", features = [\"string\"] }}\npercent-encoding = \"2\"\nreqwest = {{ version = \"0.12\", default-features = false, features = [\"json\", \"rustls-tls\"] }}\nserde_json = \"1\"\ntokio = {{ version = \"1\", features = [\"macros\", \"rt-multi-thread\"] }}\n\n[[bin]]\nname = {}\npath = \"src/main.rs\"\n",
        json_str(crate_name),
        json_str(version),
        json_str(edition),
        json_str(bin_name)
    )
}
