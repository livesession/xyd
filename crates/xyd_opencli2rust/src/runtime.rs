//! The vendored Rust runtime + user scaffolds — port of runtime.ts. The static
//! blobs live in `blobs.rs` (byte-exact); config.rs + Cargo.toml are spec-
//! interpolated here.

use serde_json::Value;

use crate::blobs;
use crate::naming::{screaming_snake_case, snake_case};
use crate::rslit::json_str;

const HEADER: &str = "// Code generated by opencli2rust. DO NOT EDIT.";

pub fn http_rs() -> String {
    blobs::HTTP_RS.to_string()
}
/// `src/gen/runtime/mod.rs` — additionally declares/re-exports `actions` + `commands`
/// when the doc has non-API runnable leaves. Kept byte-identical to the base blob
/// otherwise.
pub fn runtime_mod_rs(has_actions: bool) -> String {
    if !has_actions {
        return blobs::RUNTIME_MOD_RS.to_string();
    }
    blobs::RUNTIME_MOD_RS
        .replace(
            "pub mod config;\n",
            "mod actions;\npub mod commands;\npub mod config;\n",
        )
        .replace(
            "pub use custom::CustomCommands;\n",
            "pub use actions::Actions;\npub use commands::{bind, Commands};\npub use custom::CustomCommands;\n",
        )
}

/// `src/gen/runtime/commands.rs` — one required trait method per non-API leaf + a
/// `bind::<C>()` that registers each into the `Actions` registry, so a missing impl
/// is a COMPILE error. Only emitted when the doc has non-API runnable leaves.
pub fn commands_rs(action_paths: &[Vec<String>]) -> String {
    let methods: Vec<String> = action_paths
        .iter()
        .map(|p| {
            let name = snake_case(&p.join("-"));
            format!("    fn {name}(ctx: Context, m: ArgMatches) -> Pin<Box<dyn Future<Output = Result<(), Error>>>>;")
        })
        .collect();
    let binds: Vec<String> = action_paths
        .iter()
        .map(|p| {
            let name = snake_case(&p.join("-"));
            let path = p.iter().map(|n| json_str(n)).collect::<Vec<_>>().join(", ");
            format!("    actions.on(&[{path}], C::{name});")
        })
        .collect();
    format!(
        "{HEADER}\n\nuse std::future::Future;\nuse std::pin::Pin;\n\nuse clap::ArgMatches;\n\nuse super::http::Error;\nuse super::{{Actions, Context}};\n\n/// One method per generated non-API leaf. Your impl type must implement all of\n/// them — the compiler names any missing method when the OpenCLI surface adds a\n/// command.\npub trait Commands {{\n{}\n}}\n\n/// Register every command's trait method into the runtime dispatch registry.\npub fn bind<C: Commands + 'static>(actions: &mut Actions) {{\n{}\n}}\n",
        methods.join("\n"),
        binds.join("\n")
    )
}
pub fn overrides_rs() -> String {
    blobs::OVERRIDES_RS.to_string()
}
pub fn custom_registry_rs() -> String {
    blobs::CUSTOM_REGISTRY_RS.to_string()
}
pub fn actions_rs() -> String {
    blobs::ACTIONS_RS.to_string()
}
/// `src/<impl_module>/mod.rs` scaffold — for a doc with non-API runnable leaves it
/// carries an `impl Commands for Custom` with each leaf stubbed; otherwise it's the
/// base blob. In both cases the generated-module use path is retargeted (a no-op when
/// `module == "gen"`). Byte-identical to the base blob when `!has_actions && module == "gen"`.
pub fn custom_scaffold_rs(has_actions: bool, module: &str, action_paths: &[Vec<String>]) -> String {
    if !has_actions {
        // `crate::gen::` never appears inside any other token, so this is a no-op
        // when `module == "gen"`.
        return blobs::CUSTOM_SCAFFOLD_RS.replace("crate::gen::", &format!("crate::{module}::"));
    }

    let impl_methods = action_paths
        .iter()
        .map(|p| {
            let name = snake_case(&p.join("-"));
            format!(
                "    fn {name}(ctx: Context, m: ArgMatches) -> Pin<Box<dyn Future<Output = Result<(), Error>>>> {{\n        Box::pin(async move {{\n            let _ = (ctx, m);\n            Err(Error::Invalid(\"{name} not implemented\".into()))\n        }})\n    }}"
            )
        })
        .collect::<Vec<_>>()
        .join("\n");

    // Raw-string template with token placeholders (`__MODULE__`/`__IMPL_METHODS__`) so
    // the literal `{`/`}` in the scaffold need no format!-escaping — the TS side uses a
    // plain template literal, so this must stay byte-for-byte identical.
    let template = r#"//! Yours — scaffolded once by opencli2rust, never overwritten by regeneration.
//!
//! Two extension seams, both optional:
//!  * `CliOverrides` on [`Custom`] — hook/override every generated command
//!    (see src/gen/runtime/overrides.rs for the available methods).
//!  * [`register`] — add fully custom commands anywhere in the tree; a command
//!    registered on an existing path takes over that command's behavior.
//!  * [`Commands`] — one required method per generated non-API leaf (dev/build/…);
//!    the compiler names any you forget to implement.

use std::future::Future;
use std::pin::Pin;

use clap::ArgMatches;

use crate::__MODULE__::runtime::{CliOverrides, Commands, Context, CustomCommands, Error};

/// Override only what you need — every trait method has a default.
pub struct Custom;

impl CliOverrides for Custom {}

/// Behavior for every generated non-API leaf. Each method is stubbed — replace the
/// body with your implementation.
impl Commands for Custom {
__IMPL_METHODS__
}

/// Register hand-written commands. Called by the generated `main`.
pub fn register(commands: &mut CustomCommands) {
    let _ = commands;
    // Example — a fully custom `tools hello` subcommand:
    //
    // commands.add(&["tools"], clap::Command::new("hello").about("Say hello"), |_ctx, _m| async move {
    //     println!("hello");
    //     Ok(())
    // });
}

pub fn overrides() -> Custom {
    Custom
}
"#;
    template
        .replace("__MODULE__", module)
        .replace("__IMPL_METHODS__", &impl_methods)
}
pub fn gen_mod_rs() -> String {
    blobs::GEN_MOD_RS.to_string()
}
/// `src/main.rs` — the wiring seam. Retargets the generated (`gen`) and impl
/// (`custom`) module tokens; a no-op when `module == "gen" && impl_mod == "custom"`.
pub fn main_rs(has_actions: bool, module: &str, impl_mod: &str) -> String {
    let base = if has_actions {
        blobs::MAIN_LOCAL_RS
    } else {
        blobs::MAIN_RS
    };
    // Token-safe: `mod gen;`/`mod custom;` are unique; `gen::` never occurs inside
    // "generated" and `custom::` never inside "CustomCommands" (both lack `::`).
    base.replace("mod gen;", &format!("mod {module};"))
        .replace("mod custom;", &format!("mod {impl_mod};"))
        .replace("gen::", &format!("{module}::"))
        .replace("custom::", &format!("{impl_mod}::"))
}

/// One environment-based auth attach block, or None for an unrecognized kind.
fn auth_block(scheme: &Value) -> Option<String> {
    let env = scheme
        .get("envVar")
        .and_then(|v| v.as_str())
        .unwrap_or("API_KEY");
    let name = scheme.get("name").and_then(|v| v.as_str()).unwrap_or("");
    match scheme.get("kind").and_then(|k| k.as_str()) {
        Some("bearer") => Some(format!(
            "    if let Ok(v) = std::env::var({}) {{\n        if !v.is_empty() {{\n            rb = rb.bearer_auth(v);\n        }}\n    }}",
            json_str(env)
        )),
        Some("apiKey-header") => Some(format!(
            "    if let Ok(v) = std::env::var({}) {{\n        if !v.is_empty() {{\n            rb = rb.header({}, v);\n        }}\n    }}",
            json_str(env),
            json_str(name)
        )),
        Some("apiKey-query") => Some(format!(
            "    if let Ok(v) = std::env::var({}) {{\n        if !v.is_empty() {{\n            rb = rb.query(&[({}, v.as_str())]);\n        }}\n    }}",
            json_str(env),
            json_str(name)
        )),
        Some("apiKey-cookie") => Some(format!(
            "    if let Ok(v) = std::env::var({}) {{\n        if !v.is_empty() {{\n            rb = rb.header(\"Cookie\", format!(\"{{}}={{}}\", {}, v));\n        }}\n    }}",
            json_str(env),
            json_str(name)
        )),
        Some("basic") => Some(format!(
            "    let user = std::env::var({}).unwrap_or_default();\n    let pass = std::env::var({}).unwrap_or_default();\n    if !user.is_empty() || !pass.is_empty() {{\n        rb = rb.basic_auth(user, Some(pass));\n    }}",
            json_str(&format!("{env}_USERNAME")),
            json_str(&format!("{env}_PASSWORD"))
        )),
        _ => None,
    }
}

/// `src/gen/runtime/config.rs` — base URL + auth derived from the root x-openapi.
pub fn config_rs(spec: &Value, bin_name: &str, base_url: &str) -> String {
    let prefix = screaming_snake_case(bin_name);
    let empty: Vec<Value> = Vec::new();
    let security = spec
        .get("x-openapi")
        .and_then(|x| x.get("security"))
        .and_then(|s| s.as_array())
        .unwrap_or(&empty);
    let blocks: Vec<String> = security.iter().filter_map(auth_block).collect();

    let apply_auth = if !blocks.is_empty() {
        format!(
            "/// Attach credentials read from the environment to the request.\npub fn apply_auth(mut rb: reqwest::RequestBuilder) -> reqwest::RequestBuilder {{\n{}\n    rb\n}}",
            blocks.join("\n")
        )
    } else {
        "/// Attach credentials read from the environment to the request.\npub fn apply_auth(rb: reqwest::RequestBuilder) -> reqwest::RequestBuilder {\n    rb\n}".to_string()
    };

    format!(
        "{HEADER}\n\n//! Spec-derived configuration: the API base URL and environment-based auth.\n\nconst DEFAULT_BASE_URL: &str = {};\n\n/// The API base URL, overridable via `{prefix}_BASE_URL`.\npub fn base_url() -> String {{\n    match std::env::var({}) {{\n        Ok(v) if !v.is_empty() => v,\n        _ => DEFAULT_BASE_URL.to_string(),\n    }}\n}}\n\n{apply_auth}\n",
        json_str(base_url),
        json_str(&format!("{prefix}_BASE_URL"))
    )
}

/// `Cargo.toml` (skipIfExists) — the crate manifest.
pub fn cargo_toml(spec: &Value, crate_name: &str, bin_name: &str, edition: &str) -> String {
    let version = spec
        .get("info")
        .and_then(|i| i.get("version"))
        .and_then(|v| v.as_str())
        .unwrap_or("0.1.0");
    format!(
        "# Generated once by opencli2rust — yours to edit; regeneration never overwrites it.\n\n[package]\nname = {}\nversion = {}\nedition = {}\n\n[dependencies]\nclap = {{ version = \"4\", features = [\"string\"] }}\npercent-encoding = \"2\"\nreqwest = {{ version = \"0.12\", default-features = false, features = [\"json\", \"rustls-tls\"] }}\nserde_json = \"1\"\ntokio = {{ version = \"1\", features = [\"macros\", \"rt-multi-thread\"] }}\n\n[[bin]]\nname = {}\npath = \"src/main.rs\"\n",
        json_str(crate_name),
        json_str(version),
        json_str(edition),
        json_str(bin_name)
    )
}
