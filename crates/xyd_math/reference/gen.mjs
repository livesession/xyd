// KaTeX reference oracle generator for the xyd_math functional-equivalence gate.
//
// Reads the shared corpus (`../tests/corpus.json`) and, for each expression,
// renders it with REAL KaTeX (`output: "mathml"`, so we get just the MathML Core
// tree KaTeX produces — the same `<math>` that lives in `.katex-mathml`). It
// extracts the `<math>…</math>` subtree and writes `../tests/katex-reference.json`.
//
// This is the repo's "env-gated oracle" pattern (cf. the OpenCLI / OpenSDK
// pipelines): the committed reference JSON lets `cargo test` run OFFLINE, and this
// script is only re-run to regenerate it. KaTeX is a peer of `rehype-katex`
// (xyd-content's real math renderer), so the reference is the exact engine xyd
// ships today.
//
// Run:
//   cd crates/xyd_math/reference && npm install && node gen.mjs
//   # or from repo root: XYD_MATH_BUILD_REF=1 handled by the shell wrapper below.

import katex from "katex";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const corpusPath = join(here, "..", "tests", "corpus.json");
const outPath = join(here, "..", "tests", "katex-reference.json");

const corpus = JSON.parse(readFileSync(corpusPath, "utf8"));

// Extract the `<math …>…</math>` element out of KaTeX's `output:"mathml"` HTML
// (which wraps it in `<span class="katex"><span class="katex-mathml">…`).
function extractMath(html) {
  const start = html.indexOf("<math");
  const end = html.indexOf("</math>");
  if (start === -1 || end === -1) return null;
  return html.slice(start, end + "</math>".length);
}

const expressions = [];
for (const { id, latex, display } of corpus.expressions) {
  let katex_mathml = null;
  let katex_error = null;
  try {
    const html = katex.renderToString(latex, {
      output: "mathml",
      displayMode: display === "block",
      throwOnError: true,
      strict: false,
    });
    katex_mathml = extractMath(html);
    if (!katex_mathml) katex_error = "no <math> element in KaTeX output";
  } catch (e) {
    katex_error = String(e && e.message ? e.message : e);
  }
  expressions.push({ id, latex, display, katex_mathml, katex_error });
}

const out = {
  _comment:
    "GENERATED by reference/gen.mjs from tests/corpus.json — do not hand-edit. Real-KaTeX MathML reference for the functional-equivalence gate in tests/equivalence.rs.",
  katex_version: katex.version ?? "unknown",
  generated_at: new Date().toISOString(),
  expressions,
};

writeFileSync(outPath, JSON.stringify(out, null, 2) + "\n");
const failed = expressions.filter((e) => e.katex_error);
console.log(
  `katex ${out.katex_version}: wrote ${expressions.length} references to ${outPath}` +
    (failed.length ? `  (${failed.length} KaTeX errors: ${failed.map((f) => f.id).join(", ")})` : "")
);
