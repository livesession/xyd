//! The machine-ownership header, shared by the emitters that wrap their output
//! in one.
//!
//! Port of `packages/xyd-opensdk-framework/src/orchestrator.ts` (`fileExtension`
//! / `renderFileHeader` / `withFileHeader`). Before this module the five wrapping
//! emitters each had their own gate: go `.go`, ruby `.rb` (with no idempotency
//! check), rust `.rs`, node a two-entry table, python a path-free always-`#`
//! helper.
//!
//! WHY ADOPTING THE FULL TABLE IS OUTPUT-NEUTRAL. It is strictly wider than any
//! single crate's gate, so the question is whether some file that previously got
//! no header now gets one. Census of every extension appearing in every golden
//! tree (packages + crate-local CLI fixtures):
//!
//!   go {go, mod} · node {ts, json, md} · python {py, toml} · ruby {rb, gemspec}
//!   rust {rs, toml} · java {java, xml} · dotnet {cs, csproj}
//!
//! The table below is {go, ts, js, rs, py, rb, yaml, yml, sh}. Its intersection
//! with the previously-unheadered extensions — mod, json, md, toml, gemspec,
//! java, xml, cs, csproj — is EMPTY, so no file changes.
//!
//! java and dotnet are deliberately absent from this module. `.java`/`.cs` are
//! not in the table (upstream TS emits no orchestrator header for them); both
//! bake a language-idiomatic marker INSIDE file assembly instead — dotnet a
//! 4-line `<auto-generated>` block plus `#nullable enable`. That content is part
//! of the artifact, not a wrapper, and routing it through here would rewrite
//! their goldens.

/// The ownership header text, without any comment prefix.
pub const FILE_HEADER: &str = "Code generated by opensdk. DO NOT EDIT.";

/// Comment syntax for the ownership header, by file extension. Extensions absent
/// here never get a header — a comment would corrupt them (`.json`) or has no
/// idiomatic syntax in that language.
const HEADER_COMMENT_BY_EXT: &[(&str, &str)] = &[
    (".go", "// "),
    (".ts", "// "),
    (".js", "// "),
    (".rs", "// "),
    (".py", "# "),
    (".rb", "# "),
    (".yaml", "# "),
    (".yml", "# "),
    (".sh", "# "),
];

/// The dot-extension of a rel path (`""` for none/dotfiles),
/// e.g. `pkg/client.go` -> `.go`.
pub fn file_extension(rel_path: &str) -> &str {
    let base = rel_path.rsplit('/').next().unwrap_or(rel_path);
    match base.rfind('.') {
        // `dot > 0` keeps dotfiles (`.gitignore`) extensionless, matching the TS.
        Some(dot) if dot > 0 => &base[dot..],
        _ => "",
    }
}

/// The header rendered as a comment for `rel_path`, or `None` when the extension
/// has no known comment syntax.
pub fn render_file_header(rel_path: &str) -> Option<String> {
    HEADER_COMMENT_BY_EXT
        .iter()
        .find(|(ext, _)| *ext == file_extension(rel_path))
        .map(|(_, prefix)| format!("{prefix}{FILE_HEADER}"))
}

/// Prepend the rendered ownership header + one blank line, exactly once.
/// Content that already starts with the rendered header is returned untouched,
/// as are files whose extension has no comment syntax.
pub fn with_file_header(rel_path: &str, content: String) -> String {
    let Some(rendered) = render_file_header(rel_path) else {
        return content;
    };
    if content.starts_with(&rendered) {
        return content;
    }
    format!("{rendered}\n\n{content}")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn extension_parsing_matches_the_ts() {
        assert_eq!(file_extension("pkg/client.go"), ".go");
        assert_eq!(file_extension("client.go"), ".go");
        assert_eq!(file_extension("go.mod"), ".mod");
        assert_eq!(file_extension("README"), "");
        // A dotfile is extensionless (`dot > 0`), not `.gitignore`.
        assert_eq!(file_extension(".gitignore"), "");
        // Only the basename is considered.
        assert_eq!(file_extension("a.b/c"), "");
    }

    #[test]
    fn prefixes_match_each_language() {
        assert!(with_file_header("a.go", "package x".into()).starts_with("// Code generated"));
        assert!(with_file_header("a.rs", "fn x".into()).starts_with("// Code generated"));
        assert!(with_file_header("a.ts", "export".into()).starts_with("// Code generated"));
        assert!(with_file_header("a.py", "import x".into()).starts_with("# Code generated"));
        assert!(with_file_header("a.rb", "module X".into()).starts_with("# Code generated"));
    }

    /// The output-neutrality argument in the module doc, as a test: every
    /// extension that appears in a golden tree WITHOUT a header today must stay
    /// unheadered. A future table entry for any of these silently rewrites
    /// thousands of goldens.
    #[test]
    fn previously_unheadered_extensions_stay_untouched() {
        for path in [
            "go.mod",
            "package.json",
            "README.md",
            "pyproject.toml",
            "Cargo.toml",
            "acme.gemspec",
            "Client.java",
            "pom.xml",
            "Client.cs",
            "Acme.csproj",
        ] {
            assert_eq!(
                with_file_header(path, "BODY".into()),
                "BODY",
                "{path} must not gain a header"
            );
        }
    }

    #[test]
    fn header_is_applied_exactly_once() {
        let once = with_file_header("a.go", "package x".into());
        assert_eq!(with_file_header("a.go", once.clone()), once);
    }
}
