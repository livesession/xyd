//! javawriter.ts — the ownership header, file assembly, and Javadoc helper.

use crate::jsrt::unique_sorted;

pub const HEADER: &str = "Code generated by opensdk. DO NOT EDIT.";

/// Assemble a `.java` file: header + package + (deduped, sorted) imports + body.
pub fn java_file(pkg: &str, imports: &[String], body: &str) -> String {
    let mut parts: Vec<String> = vec![
        format!("// {HEADER}"),
        String::new(),
        format!("package {pkg};"),
    ];
    let uniq = unique_sorted(imports);
    if !uniq.is_empty() {
        parts.push(String::new());
        parts.push(
            uniq.iter()
                .map(|i| format!("import {i};"))
                .collect::<Vec<_>>()
                .join("\n"),
        );
    }
    parts.push(String::new());
    parts.push(body.trim_end().to_string());
    format!("{}\n", parts.join("\n"))
}

/// A Javadoc block, or "" when empty.
pub fn java_doc(text: Option<&str>, indent: &str) -> String {
    let raw = text.unwrap_or("").trim();
    if raw.is_empty() {
        return String::new();
    }
    let lines: Vec<&str> = raw.split('\n').collect();
    if lines.len() == 1 {
        return format!("{indent}/** {} */", lines[0].trim());
    }
    let body = lines
        .iter()
        .map(|l| format!("{indent} * {}", l.trim()))
        .collect::<Vec<_>>()
        .join("\n");
    format!("{indent}/**\n{body}\n{indent} */")
}
