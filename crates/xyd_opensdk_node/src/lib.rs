//! `xyd_opensdk_node` — pure Rust port of the generated-code slice of the
//! `@xyd-js/opensdk-node` emitter (OpenSDK IR → an openai-node-shaped TypeScript
//! SDK). W7 of the S6+ Rust migration.
//!
//! Scope: the substantive IR→TypeScript emission — `package.json` / `tsconfig.json`
//! / `README.md`, `src/index.ts`, `src/client.ts`, `src/models.ts`,
//! `src/resources/index.ts`, `src/resources/<resource>.ts`. Deferred (not ported
//! here): the vendored fixed `src/core/**` runtime, the generated `tests/**`, the
//! optional busybox helpers, `publish.ts`, and the napi surface + JS shim.
//!
//! Entry point: [`generate_node`] — pure, IR JSON in, virtual file map out.

use std::collections::BTreeMap;

mod behavior;
mod client;
mod ir;
mod jsrt;
mod model;
mod plan;
mod project;
mod resource;

use ir::Spec;
use resource::NodeCtx;

/// The machine-ownership marker prepended (as `// …`) to every generated `.ts`
/// file — matches `nodeEmitter.fileHeader()`.
const FILE_HEADER: &str = "Code generated by opensdk. DO NOT EDIT.";

/// Generate the buildable Node SDK's generated-code files from an OpenSDK IR
/// document. Returns a virtual file map `{ relativePath: contents }` (the
/// framework orchestrator's contract, minus the deferred runtime/test files).
pub fn generate_node(spec_json: &serde_json::Value) -> BTreeMap<String, String> {
    let spec: Spec = serde_json::from_value(spec_json.clone())
        .expect("OpenSDK IR did not match the expected shape");
    generate_from_spec(&spec)
}

fn generate_from_spec(spec: &Spec) -> BTreeMap<String, String> {
    let opts = project::resolve_node_options(spec);
    let error_classes = behavior::error_class_names(spec);
    let types: Vec<&ir::NamedType> = spec.types.iter().collect();
    let auto_generate_for_post = spec
        .sdk
        .as_ref()
        .and_then(|s| s.idempotency.as_ref())
        .and_then(|i| i.auto_generate_for_post)
        .unwrap_or(true);
    let ctx = NodeCtx {
        types,
        auto_generate_for_post,
    };

    let mut files: BTreeMap<String, String> = BTreeMap::new();
    let mut add = |path: &str, content: String| {
        let content = with_file_header(path, content);
        if files.insert(path.to_string(), content).is_some() {
            panic!("emitter \"node\": re-emitted {path}");
        }
    };

    // generateProject (no ownership header on .json / .md)
    add("package.json", project::package_json(&opts.pkg, spec));
    add("tsconfig.json", project::tsconfig_json());
    add(
        "README.md",
        project::readme(&opts.pkg, spec, &opts.client_name, opts.default_export),
    );

    // generateClient
    add(
        "src/index.ts",
        client::render_root_index_file(
            spec,
            &error_classes,
            &opts.client_name,
            opts.default_export,
        ),
    );
    add(
        "src/client.ts",
        client::render_client_file(spec, &opts.env_var, &opts.client_name),
    );

    // generateTypes
    add("src/models.ts", model::render_models_file(spec));

    // generateResources
    if !spec.resources.is_empty() {
        for r in &spec.resources {
            let (path, content) = resource::render_resource_file(r, &ctx);
            add(&path, content);
        }
        add(
            "src/resources/index.ts",
            resource::render_resources_index_file(&spec.resources),
        );
    }

    files
}

/// The dot-extension of a rel path ('' for none/dotfiles).
fn file_extension(rel_path: &str) -> &str {
    let base = rel_path.rsplit('/').next().unwrap_or(rel_path);
    match base.rfind('.') {
        Some(dot) if dot > 0 => &base[dot..],
        _ => "",
    }
}

/// Prepend the rendered ownership header + one blank line for `.ts` files
/// (other extensions have no idiomatic comment here → untouched).
fn with_file_header(rel_path: &str, content: String) -> String {
    // Only .ts is produced by this generator; keep the ext gate faithful.
    let prefix = match file_extension(rel_path) {
        ".ts" | ".js" => "// ",
        _ => return content,
    };
    let rendered = format!("{prefix}{FILE_HEADER}");
    if content.starts_with(&rendered) {
        content
    } else {
        format!("{rendered}\n\n{content}")
    }
}
