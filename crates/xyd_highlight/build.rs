fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let assets = manifest.join("assets");
    let grammars_dir = assets.join("grammars");
    let themes_dir = assets.join("themes");
    let lang_data = assets.join("lang-data.json");

    println!("cargo:rerun-if-changed=assets");
    println!("cargo:rerun-if-changed=build.rs");

    let core_only = env::var_os("CARGO_FEATURE_CORE_LANGS").is_some();

    let mut grammars: Vec<(String, PathBuf)> = list(&grammars_dir, ".json.zst");
    if core_only {
        grammars.retain(|(id, _)| CORE_LANG_IDS.contains(&id.as_str()));
    }
    grammars.sort();
    let themes: Vec<(String, PathBuf)> = {
        let mut t = list(&themes_dir, ".json");
        t.sort();
        t
    };

    let mut out = String::new();
    out.push_str("// @generated by build.rs — do not edit.\n\n");

    let mut store_bytes: usize = 0;
    writeln!(out, "pub static GRAMMAR_STORE: &[(&str, &[u8])] = &[").unwrap();
    for (id, path) in &grammars {
        store_bytes += fs::metadata(path).map(|m| m.len() as usize).unwrap_or(0);
        writeln!(out, "    ({:?}, include_bytes!({:?})),", id, path).unwrap();
    }
    writeln!(out, "];\n").unwrap();

    writeln!(out, "pub static THEME_STORE: &[(&str, &str)] = &[").unwrap();
    for (name, path) in &themes {
        writeln!(out, "    ({:?}, include_str!({:?})),", name, path).unwrap();
    }
    writeln!(out, "];\n").unwrap();

    writeln!(
        out,
        "pub static LANG_DATA_JSON: &str = include_str!({:?});\n",
        lang_data
    )
    .unwrap();

    writeln!(
        out,
        "/// Compressed on-disk size of the embedded grammar store, in bytes."
    )
    .unwrap();
    writeln!(out, "pub const GRAMMAR_STORE_BYTES: usize = {store_bytes};").unwrap();

    let out_path = Path::new(&env::var("OUT_DIR").unwrap()).join("store.rs");
    fs::write(&out_path, out).unwrap();
}

/// List `(stem, path)` for every file in `dir` ending in `suffix`, where `stem`
/// is the filename with `suffix` stripped.
fn list(dir: &Path, suffix: &str) -> Vec<(String, PathBuf)> {
    let mut v = Vec::new();
    let Ok(entries) = fs::read_dir(dir) else {
        panic!(
            "missing assets dir {} — run scripts/vendor-assets.mjs",
            dir.display()
        );
    };
    for e in entries.flatten() {
        let name = e.file_name().to_string_lossy().into_owned();
        if let Some(stem) = name.strip_suffix(suffix) {
            v.push((stem.to_string(), e.path()));
        }
    }
    v
}
