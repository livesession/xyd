//! Build-time embedded store generator.
//!
//! Walks `assets/grammars/*.json.zst` + `assets/themes/*.json` (vendored by
//! `scripts/vendor-assets.mjs`) and emits `$OUT_DIR/store.rs`, which `include_
//! bytes!`s each compressed grammar and `include_str!`s each raw theme behind
//! `id/name -> &'static [u8]/&'static str` slices. The runtime Registry
//! (`src/store.rs`) lazily zstd-decompresses + parses grammars on first use.
//!
//! The `core-langs` feature trims the embedded grammar set to the transitive
//! closure of the top-20 docs languages (their cross-grammar embeds included),
//! so size-sensitive `bun --compile` builds don't carry the long tail. The
//! default build embeds all 254.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

