// Tiny Rust-source string helpers (the golit.ts analogue for clap builder chains):
// just enough to render method-call chains with correct indentation — not an AST.

const UNIT = '    '; // 4-space Rust indentation
const pad = (n: number) => UNIT.repeat(n);

/** A value renderer: its first line is emitted inline; nested lines indent to `indent`. */
export type RsVal = (indent: number) => string;

/** A pre-rendered scalar (identifier, number, expression). */
export const lit = (s: string): RsVal => () => s;

/** A Rust double-quoted string literal (JSON escaping is Rust-compatible for our content). */
export const rsStr = (s: string): RsVal => () => JSON.stringify(s);

/**
 * A builder-method chain: `base` inline, then one `.method(args)` per line at
 * `indent + 1`. A multiline argument goes on its own lines (rustfmt style):
 *
 *     Command::new("models")
 *         .about("...")
 *         .subcommand(
 *             Command::new("list"),
 *         )
 */
export function chain(base: string, calls: [method: string, args: RsVal[]][]): RsVal {
  return (indent: number) => {
    let out = base;
    for (const [method, args] of calls) {
      const rendered = args.map((a) => a(indent + 2));
      if (rendered.some((r) => r.includes('\n'))) {
        const block = rendered.map((r) => `${pad(indent + 2)}${r},`).join('\n');
        out += `\n${pad(indent + 1)}.${method}(\n${block}\n${pad(indent + 1)})`;
      } else {
        out += `\n${pad(indent + 1)}.${method}(${rendered.join(', ')})`;
      }
    }
    return out;
  };
}

/** Render a top-level value (indent 0). */
export function render(v: RsVal): string {
  return v(0);
}

/** Indent every non-empty line of `text` by `levels` indent units (blank lines stay blank). */
export function indent(text: string, levels = 1): string {
  const p = pad(levels);
  return text
    .split('\n')
    .map((line) => (line.length ? p + line : line))
    .join('\n');
}

/** Tracks the `use` items a generated file needs, rendered as one sorted block. */
export class Uses {
  private items = new Set<string>();

  add(...uses: string[]): this {
    for (const u of uses) this.items.add(u);
    return this;
  }

  get size(): number {
    return this.items.size;
  }

  /** Groups: std first, external crates next, `crate::`/`super::` last — blank-line separated. */
  render(): string {
    if (this.items.size === 0) return '';
    const all = [...this.items];
    const std = all.filter((u) => u.startsWith('std::')).sort();
    const local = all.filter((u) => /^(crate|super|self)::/.test(u)).sort();
    const ext = all.filter((u) => !std.includes(u) && !local.includes(u)).sort();
    const groups = [std, ext, local].filter((g) => g.length > 0);
    return groups.map((g) => g.map((u) => `use ${u};`).join('\n')).join('\n\n');
  }
}

/** Assemble a complete generated Rust file: ownership header + uses + declarations. */
export function rsFile(uses: Uses, decls: string[], header = GENERATED_HEADER): string {
  const parts: string[] = [];
  if (header) parts.push(header);
  if (uses.size > 0) parts.push(uses.render());
  parts.push(...decls);
  return `${parts.join('\n\n')}\n`;
}

/** The ownership header stamped on every generator-owned file. */
export const GENERATED_HEADER = '// Code generated by opencli2rust. DO NOT EDIT.';
