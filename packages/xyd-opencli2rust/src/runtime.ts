function authBlock(scheme: XOpenApiSecurity): string | null {
  const env = scheme.envVar || 'API_KEY';
  const name = scheme.name || '';
  switch (scheme.kind) {
    case 'bearer':
      return `    if let Ok(v) = std::env::var(${JSON.stringify(env)}) {
        if !v.is_empty() {
            rb = rb.bearer_auth(v);
        }
    }`;
    case 'apiKey-header':
      return `    if let Ok(v) = std::env::var(${JSON.stringify(env)}) {
        if !v.is_empty() {
            rb = rb.header(${JSON.stringify(name)}, v);
        }
    }`;
    case 'apiKey-query':
      return `    if let Ok(v) = std::env::var(${JSON.stringify(env)}) {
        if !v.is_empty() {
            rb = rb.query(&[(${JSON.stringify(name)}, v.as_str())]);
        }
    }`;
    case 'apiKey-cookie':
      return `    if let Ok(v) = std::env::var(${JSON.stringify(env)}) {
        if !v.is_empty() {
            rb = rb.header("Cookie", format!("{}={}", ${JSON.stringify(name)}, v));
        }
    }`;
    case 'basic':
      return `    let user = std::env::var(${JSON.stringify(`${env}_USERNAME`)}).unwrap_or_default();
    let pass = std::env::var(${JSON.stringify(`${env}_PASSWORD`)}).unwrap_or_default();
    if !user.is_empty() || !pass.is_empty() {
        rb = rb.basic_auth(user, Some(pass));
    }`;
    default:
      return null;
  }
}

/** Generated: `src/gen/runtime/config.rs` — base URL + auth derived from the spec's root x-openapi. */
export function configRs(spec: OpencliSpecJson, binName: string, baseURL: string): string {
  const prefix = screamingSnakeCase(binName);
  const security = spec['x-openapi']?.security || [];
  const blocks = security.map(authBlock).filter((b): b is string => b !== null);

  const applyAuth = blocks.length
    ? `/// Attach credentials read from the environment to the request.
pub fn apply_auth(mut rb: reqwest::RequestBuilder) -> reqwest::RequestBuilder {
${blocks.join('\n')}
    rb
}`
    : `/// Attach credentials read from the environment to the request.
pub fn apply_auth(rb: reqwest::RequestBuilder) -> reqwest::RequestBuilder {
    rb
}`;

  return `${HEADER}

//! Spec-derived configuration: the API base URL and environment-based auth.

const DEFAULT_BASE_URL: &str = ${JSON.stringify(baseURL)};

/// The API base URL, overridable via \`${prefix}_BASE_URL\`.
pub fn base_url() -> String {
    match std::env::var(${JSON.stringify(`${prefix}_BASE_URL`)}) {
        Ok(v) if !v.is_empty() => v,
        _ => DEFAULT_BASE_URL.to_string(),
    }
}

${applyAuth}
`;
}

