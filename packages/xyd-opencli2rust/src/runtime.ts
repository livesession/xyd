// The vendored Rust runtime + user-owned scaffolds, embedded as template strings
// (the runtime.ts pattern from xyd-opencli2go). One deliberate divergence from the
// Go runtime: execution RETURNS the decoded value instead of printing inside Do —
// printing lives exclusively in the CliOverrides trait so custom code owns output.

import type { OpencliSpecJson, XOpenApiSecurity } from '@xyd-js/opencli';

import { screamingSnakeCase } from './naming';

const HEADER = '// Code generated by opencli2rust. DO NOT EDIT.';

/** Static: `src/gen/runtime/http.rs` — request/error primitives. */
export function httpRs(): string {
  return `${HEADER}

//! Static HTTP primitives shared by every command handler.

use percent_encoding::{utf8_percent_encode, AsciiSet, NON_ALPHANUMERIC};
use serde_json::Value;

/// Escape a value for use inside a URL path segment (strict RFC 3986 unreserved).
const PATH_SEGMENT: &AsciiSet = &NON_ALPHANUMERIC.remove(b'-').remove(b'_').remove(b'.').remove(b'~');

pub fn path_escape(value: &str) -> String {
    utf8_percent_encode(value, PATH_SEGMENT).to_string()
}

/// A generic API request assembled by a command handler.
pub struct Request {
    pub method: &'static str,
    pub path: String,
    pub query: Vec<(&'static str, String)>,
    pub headers: Vec<(&'static str, String)>,
    pub body: Option<Vec<u8>>,
}

/// A request failure, inspectable from \`CliOverrides::recover_error\` / \`print_error\`.
#[derive(Debug)]
pub enum Error {
    /// The server answered with a 4xx/5xx status; \`body\` is the decoded response.
    Http { status: u16, body: Value },
    /// The request could not be sent or the response could not be read.
    Transport(String),
    /// A handler-side failure (flag decoding, body assembly, custom command logic).
    Invalid(String),
}

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Error::Http { status, body } => write!(f, "request failed: {status}: {body}"),
            Error::Transport(message) => write!(f, "request error: {message}"),
            Error::Invalid(message) => write!(f, "{message}"),
        }
    }
}

impl std::error::Error for Error {}

/// Decode a response body: JSON when it parses, the raw text otherwise.
pub(crate) fn decode(bytes: &[u8]) -> Value {
    serde_json::from_slice(bytes).unwrap_or_else(|_| Value::String(String::from_utf8_lossy(bytes).into_owned()))
}
`;
}

/** Static: `src/gen/runtime/mod.rs` — Context (execution) + run_request (hook threading). */
export function runtimeModRs(hasActions: boolean): string {
  const actionMod = hasActions ? 'mod actions;\n' : '';
  const actionUse = hasActions ? 'pub use actions::Actions;\n' : '';
  return `${HEADER}

//! The vendored runtime: request execution context, override hooks, and the
//! custom-command registry. Extension points live in \`overrides.rs\` (the
//! \`CliOverrides\` trait) and \`custom.rs\` (the \`CustomCommands\` registry).

${actionMod}pub mod config;
mod custom;
mod http;
mod overrides;

${actionUse}pub use custom::CustomCommands;
pub use http::{path_escape, Error, Request};
pub use overrides::CliOverrides;

use std::process::ExitCode;

use serde_json::Value;

/// Everything a handler (generated or custom) needs to reach the API: the
/// configured base URL and an HTTP client with the spec's auth applied.
#[derive(Clone)]
pub struct Context {
    pub base_url: String,
    http: reqwest::Client,
}

impl Context {
    pub fn from_env() -> Self {
        Self {
            base_url: config::base_url(),
            http: reqwest::Client::new(),
        }
    }

    /// Execute against the configured base URL with the spec's auth applied,
    /// decoding the response (JSON when it parses, raw text otherwise).
    pub async fn execute(&self, req: Request) -> Result<Value, Error> {
        let (status, bytes) = self.send(req).await?;
        let value = http::decode(&bytes);
        if status >= 400 {
            return Err(Error::Http { status, body: value });
        }
        Ok(value)
    }

    /// Raw-bytes variant of [\`execute\`](Self::execute) for binary/non-JSON endpoints.
    #[allow(dead_code)] // user-facing API for custom command handlers
    pub async fn execute_raw(&self, req: Request) -> Result<Vec<u8>, Error> {
        let (status, bytes) = self.send(req).await?;
        if status >= 400 {
            return Err(Error::Http { status, body: http::decode(&bytes) });
        }
        Ok(bytes)
    }

    async fn send(&self, req: Request) -> Result<(u16, Vec<u8>), Error> {
        let endpoint = format!("{}{}", self.base_url.trim_end_matches('/'), req.path);
        let method = reqwest::Method::from_bytes(req.method.as_bytes()).map_err(|e| Error::Invalid(e.to_string()))?;
        let mut rb = self.http.request(method, &endpoint);
        if !req.query.is_empty() {
            rb = rb.query(&req.query);
        }
        let has_content_type = req.headers.iter().any(|(k, _)| k.eq_ignore_ascii_case("content-type"));
        for (key, value) in &req.headers {
            rb = rb.header(*key, value.as_str());
        }
        if let Some(body) = req.body {
            if !has_content_type {
                rb = rb.header("Content-Type", "application/json");
            }
            rb = rb.body(body);
        }
        rb = config::apply_auth(rb);
        let resp = rb.send().await.map_err(|e| Error::Transport(e.to_string()))?;
        let status = resp.status().as_u16();
        let bytes = resp.bytes().await.map_err(|e| Error::Transport(e.to_string()))?.to_vec();
        Ok((status, bytes))
    }
}

/// Thread one generated request through the override hooks: mutate, execute,
/// transform, recover, then print. Printing happens ONLY here (via the trait),
/// so overrides fully control the CLI's output.
pub async fn run_request<O: CliOverrides>(
    ctx: &Context,
    o: &O,
    cmd_path: &[String],
    mut req: Request,
) -> ExitCode {
    o.before_request(ctx, cmd_path, &mut req);
    let outcome = match ctx.execute(req).await {
        Ok(value) => o.transform_response(ctx, cmd_path, value),
        Err(err) => Err(err),
    };
    match outcome.or_else(|err| o.recover_error(ctx, cmd_path, err)) {
        Ok(value) => {
            o.print_success(cmd_path, &value);
            ExitCode::SUCCESS
        }
        Err(err) => o.print_error(cmd_path, &err),
    }
}
`;
}

/** Static: `src/gen/runtime/overrides.rs` — the CliOverrides trait (all methods defaulted + sync). */
export function overridesRs(): string {
  return `${HEADER}

use std::process::ExitCode;

use serde_json::Value;

use super::http::{Error, Request};
use super::Context;

/// The override seam for every generated command. Implement this on your type in
/// \`src/custom/mod.rs\` — every method has a default, so \`impl CliOverrides for
/// Custom {}\` compiles and behaves exactly like the stock CLI.
pub trait CliOverrides {
    /// Mutate the assembled request before it is sent (extra headers, alternate
    /// auth, tracing). \`cmd_path\` is the invoked command path, e.g. \`["models", "list"]\`.
    fn before_request(&self, ctx: &Context, cmd_path: &[String], req: &mut Request) {
        let _ = (ctx, cmd_path, req);
    }

    /// Transform the decoded response before printing.
    fn transform_response(&self, ctx: &Context, cmd_path: &[String], value: Value) -> Result<Value, Error> {
        let _ = (ctx, cmd_path);
        Ok(value)
    }

    /// Recover from a failure: return \`Ok(value)\` to turn it into a success,
    /// or hand the error back to keep failing.
    fn recover_error(&self, ctx: &Context, cmd_path: &[String], err: Error) -> Result<Value, Error> {
        let _ = (ctx, cmd_path);
        Err(err)
    }

    /// Print a successful result. Default: pretty JSON (raw text for non-JSON bodies).
    fn print_success(&self, cmd_path: &[String], value: &Value) {
        let _ = cmd_path;
        match value {
            Value::String(text) => println!("{text}"),
            other => match serde_json::to_string_pretty(other) {
                Ok(text) => println!("{text}"),
                Err(_) => println!("{other}"),
            },
        }
    }

    /// Print a failure and choose the process exit code.
    fn print_error(&self, cmd_path: &[String], err: &Error) -> ExitCode {
        let _ = cmd_path;
        eprintln!("error: {err}");
        ExitCode::FAILURE
    }
}
`;
}

/** Static: `src/gen/runtime/custom.rs` — the custom-command registry + clap grafting. */
export function customRegistryRs(): string {
  return `${HEADER}

use std::future::Future;
use std::pin::Pin;

use clap::{ArgMatches, Command};

use super::http::Error;
use super::Context;

/// The boxed async handler for one custom command (owned inputs, so plain
/// \`|ctx, m| async move { ... }\` closures fit without lifetime plumbing).
pub type CustomHandler = Box<dyn Fn(Context, ArgMatches) -> Pin<Box<dyn Future<Output = Result<(), Error>>>>>;

struct CustomEntry {
    under: Vec<String>,
    command: Command,
    handler: CustomHandler,
}

/// Hand-written commands registered from \`src/custom/mod.rs\`, grafted into the
/// generated tree before parsing and dispatched BEFORE generated handlers — a
/// custom command registered on an existing path overrides its behavior.
#[derive(Default)]
pub struct CustomCommands {
    entries: Vec<CustomEntry>,
}

impl CustomCommands {
    pub fn new() -> Self {
        Self::default()
    }

    /// Add \`command\` under a parent path (\`&[]\` = top level):
    /// \`add(&["tools"], Command::new("hello"), |ctx, m| async move { ... })\`
    /// registers \`<bin> tools hello\`. Missing parents are created. When the full
    /// path already exists in the generated tree, the generated clap definition
    /// keeps handling parsing/help, but YOUR handler runs instead.
    #[allow(dead_code)] // user-facing API, called from src/custom/mod.rs
    pub fn add<H, F>(&mut self, under: &[&str], command: Command, handler: H)
    where
        H: Fn(Context, ArgMatches) -> F + 'static,
        F: Future<Output = Result<(), Error>> + 'static,
    {
        self.entries.push(CustomEntry {
            under: under.iter().map(|s| s.to_string()).collect(),
            command,
            handler: Box::new(move |ctx, m| Box::pin(handler(ctx, m))),
        });
    }

    /// Graft registered commands into the generated clap tree (new paths only —
    /// existing definitions are left untouched; dispatch still prefers custom).
    pub(crate) fn graft(&self, mut root: Command) -> Command {
        for entry in &self.entries {
            let mut full = entry.under.clone();
            full.push(entry.command.get_name().to_string());
            if path_exists(&root, &full) {
                continue;
            }
            root = graft_at(root, &entry.under, entry.command.clone());
        }
        root
    }

    /// The handler registered for exactly this invoked command path, if any.
    pub(crate) fn find(&self, path: &[String]) -> Option<&CustomHandler> {
        self.entries
            .iter()
            .find(|e| {
                e.under.len() + 1 == path.len()
                    && e.under.iter().zip(path.iter()).all(|(a, b)| a == b)
                    && path.last().map(String::as_str) == Some(e.command.get_name())
            })
            .map(|e| &e.handler)
    }
}

fn path_exists(root: &Command, path: &[String]) -> bool {
    let mut current = root;
    for name in path {
        match current.find_subcommand(name) {
            Some(sub) => current = sub,
            None => return false,
        }
    }
    true
}

fn graft_at(parent: Command, under: &[String], cmd: Command) -> Command {
    match under.split_first() {
        None => parent.subcommand(cmd),
        Some((head, rest)) => {
            let rest = rest.to_vec();
            if parent.find_subcommand(head).is_some() {
                parent.mut_subcommand(head.clone(), move |sub| graft_at(sub, &rest, cmd))
            } else {
                let node = Command::new(head.clone()).subcommand_required(true).arg_required_else_help(true);
                parent.subcommand(graft_at(node, &rest, cmd))
            }
        }
    }
}
`;
}

/**
 * Static: `src/gen/runtime/actions.rs` — the `Actions` registry (only emitted when
 * the doc has non-API runnable leaves). Parallel to `CustomCommands`: behavior for
 * generated leaves is bound by path via `Actions::on` and dispatched by `gen::cli::run`.
 */
export function actionsRs(): string {
  return `${HEADER}

use std::future::Future;
use std::pin::Pin;

use clap::ArgMatches;

use super::http::Error;
use super::Context;

/// The boxed async handler for one non-API "action" — a generated runnable leaf
/// (e.g. \`dev\`/\`build\`) whose behavior is hand-written, not an HTTP call. Owned
/// inputs, so plain \`|ctx, m| async move { ... }\` closures fit without lifetimes.
pub type Action = Box<dyn Fn(Context, ArgMatches) -> Pin<Box<dyn Future<Output = Result<(), Error>>>>>;

struct ActionEntry {
    path: Vec<String>,
    action: Action,
}

/// Behavior for the generated non-API leaves. Bind handlers from \`src/custom/mod.rs\`
/// with [\`Actions::on\`]; \`gen::cli::run\` dispatches them AFTER custom commands and
/// BEFORE the x-openapi handlers. An unbound leaf fails at runtime with a hint.
#[derive(Default)]
pub struct Actions {
    entries: Vec<ActionEntry>,
}

impl Actions {
    pub fn new() -> Self {
        Self::default()
    }

    /// Bind behavior to a generated leaf path:
    /// \`on(&["dev"], |ctx, m| async move { ... })\` handles \`<bin> dev\`,
    /// \`on(&["components", "install"], ...)\` handles \`<bin> components install\`.
    #[allow(dead_code)] // user-facing API, called from src/custom/mod.rs
    pub fn on<H, F>(&mut self, path: &[&str], action: H)
    where
        H: Fn(Context, ArgMatches) -> F + 'static,
        F: Future<Output = Result<(), Error>> + 'static,
    {
        self.entries.push(ActionEntry {
            path: path.iter().map(|s| s.to_string()).collect(),
            action: Box::new(move |ctx, m| Box::pin(action(ctx, m))),
        });
    }

    /// Run the handler bound to \`path\`, or fail with a "not implemented" hint.
    pub(crate) async fn run(&self, ctx: &Context, path: &[String], m: &ArgMatches) -> Result<(), Error> {
        match self.entries.iter().find(|e| e.path.as_slice() == path) {
            Some(entry) => (entry.action)(ctx.clone(), m.clone()).await,
            None => Err(Error::Invalid(format!(
                "not implemented — add actions.on(&{path:?}, ...) in src/custom/mod.rs"
            ))),
        }
    }
}
`;
}

