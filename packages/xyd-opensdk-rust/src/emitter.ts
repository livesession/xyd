import type { NamedType, OpensdkSpecJson, Resource } from '@xyd-js/opensdk-core';
import type { Emitter, EmitterContext, GeneratedFile } from '@xyd-js/opensdk-framework';
import { generate } from '@xyd-js/opensdk-framework';

import { renderClientFile } from './client';
import { renderModelsFile } from './model';
import { crateName, screamingSnakeCase, snakeCase } from './naming';
import { renderCargoToml, renderLibRs } from './project';
import { renderErrorFile, renderTransportFile } from './runtime';
import { type RustCtx, renderServiceFile } from './service';
import { commonModRs, resourceTestRs } from './tests-rs';
import type { OpensdkRustOptions } from './types';

interface ResolvedRustOptions {
  crate: string;
  baseURL: string;
  edition: string;
  envVar: string;
}

function resolveOptions(spec: OpensdkSpecJson, ctx: EmitterContext): ResolvedRustOptions {
  const options = ctx.emitterOptions as OpensdkRustOptions;
  const crate = options.packageName ?? options.moduleName ?? crateName(spec.info.title);
  return {
    crate,
    baseURL: options.baseURL ?? spec.servers?.[0] ?? '',
    edition: options.edition ?? '2021',
    envVar: spec.security?.find((s) => s.envVar)?.envVar ?? `${screamingSnakeCase(crate)}_API_KEY`,
  };
}

function rustCtx(spec: OpensdkSpecJson, ctx: EmitterContext): RustCtx {
  const { crate } = resolveOptions(spec, ctx);
  return { crate, types: ctx.types as Map<string, NamedType> };
}

/**
 * The Rust emitter plugin: an async reqwest + tokio + serde SDK — `Client`, one
 * resource module per top-level resource (nested, path-qualified), serde models,
 * and a vendored transport. Pure capability methods over the IR; the framework
 * orchestrator assembles the file map.
 */
export const rustEmitter: Emitter = {
  language: 'rust',

  // The machine-ownership marker: the orchestrator prepends it (as `// ...`) to
  // every generated .rs file. Cargo.toml is left untouched (unknown extension).
  fileHeader(): string {
    return 'Code generated by opensdk. DO NOT EDIT.';
  },

  generateProject(spec: OpensdkSpecJson, ctx: EmitterContext): GeneratedFile[] {
    const { crate, edition } = resolveOptions(spec, ctx);
    return [
      // User-owned scaffold: never clobber a hand-edited manifest on regen.
      { path: 'Cargo.toml', content: renderCargoToml(spec, crate, edition), writeMode: 'skipIfExists' },
      { path: 'src/lib.rs', content: renderLibRs(spec) },
    ];
  },

  generateClient(spec: OpensdkSpecJson, ctx: EmitterContext): GeneratedFile[] {
    const { envVar } = resolveOptions(spec, ctx);
    return [{ path: 'src/client.rs', content: renderClientFile(spec, envVar) }];
  },

  // models.rs is always emitted (even for an empty symbol table): lib.rs declares
  // the module unconditionally.
  generateTypes(_types: NamedType[], ctx: EmitterContext): GeneratedFile[] {
    return [{ path: 'src/models.rs', content: renderModelsFile(ctx.spec) }];
  },

  generateResources(resources: Resource[], ctx: EmitterContext): GeneratedFile[] {
    const rctx = rustCtx(ctx.spec, ctx);
    return resources.map((resource) => renderServiceFile(resource, rctx));
  },

  generateRuntime(spec: OpensdkSpecJson, ctx: EmitterContext): GeneratedFile[] {
    const { crate, baseURL } = resolveOptions(spec, ctx);
    return [
      { path: 'src/error.rs', content: renderErrorFile(spec) },
      { path: 'src/transport.rs', content: renderTransportFile(spec, crate, baseURL) },
    ];
  },

  // The SDK's own #[tokio::test] suite (tests/**): one tests/<resource>.rs per
  // top-level resource plus the shared tests/common/mod.rs. Off via
  // emitterOptions.tests === false; default ON. Example values come from the
  // shared planner so the Go/Python/Ruby/Rust suites exercise identical shapes.
  generateTests(spec: OpensdkSpecJson, ctx: EmitterContext): GeneratedFile[] {
    if ((ctx.emitterOptions as OpensdkRustOptions).tests === false) return [];
    const { crate } = resolveOptions(spec, ctx);
    const resources = spec.resources || [];
    if (resources.length === 0) return [];
    const types = ctx.types as Map<string, NamedType>;
    const files: GeneratedFile[] = [{ path: 'tests/common/mod.rs', content: commonModRs(crate) }];
    for (const r of resources) {
      files.push({ path: `tests/${snakeCase(r.name)}.rs`, content: resourceTestRs(r, crate, types) });
    }
    return files;
  },
};

/**
 * Generate a buildable, async Rust SDK from an OpenSDK IR. Back-compat wrapper:
 * drives the `rustEmitter` plugin through the framework orchestrator. Pure:
 * returns a virtual file map `{ relativePath: contents }`.
 */
export function opensdkRust(spec: OpensdkSpecJson, options: OpensdkRustOptions = {}): Record<string, string> {
  return generate(spec, rustEmitter, options as Record<string, unknown>);
}
