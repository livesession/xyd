import { describe, expect, it } from 'vitest';

import { opensdkRust } from '../index';
import { RUST_SMOKE, cargoBuildSmoke, readIR, testFixture } from './utils';

const fixtures = [
  { name: '1.basic', description: 'client, resource modules, typed async methods, serde models, reqwest transport' },
  {
    name: '2.wire',
    description:
      'wire robustness: multipart upload (Vec<u8> file part), form body, header params, wireName + explode query serialization, sdk-behavior transport (retry, timeout, UA, error kinds + request id, idempotency injection)',
  },
  {
    name: '3.unions',
    description:
      'type-system consumption: discriminated-union serde enum (tag), mapping-less untagged union, const fields, cursor/offset pagination containers',
  },
];

describe('opensdk-rust', () => {
  for (const f of fixtures) {
    it(f.description, () => {
      testFixture(f.name);
    });
  }

  if (RUST_SMOKE) {
    for (const f of fixtures) {
      it(`cargo test --no-run: ${f.name}`, () => {
        cargoBuildSmoke(f.name);
      }, 600000);
    }
  }
});

// The Rust SDK mirrors the Go/Ruby emitters: same IR in, a language-native SDK
// out, driven through the same framework orchestrator.
describe('opensdk-rust shape', () => {
  it('prepends the ownership header to every generated .rs file (and never to Cargo.toml)', () => {
    const files = opensdkRust(readIR('1.basic'));
    for (const [rel, content] of Object.entries(files)) {
      if (rel.endsWith('.rs')) {
        expect(content.startsWith('// Code generated by opensdk. DO NOT EDIT.\n\n'), rel).toBe(true);
      }
    }
    expect(files['Cargo.toml']).not.toContain('DO NOT EDIT');
    expect(files['Cargo.toml']).toContain('[package]');
  });

  it('emits the client + async resource layout', () => {
    const files = opensdkRust(readIR('1.basic'));
    expect(files['src/client.rs']).toContain('pub struct Client');
    expect(files['src/client.rs']).toContain('pub fn pets(&self) -> crate::pets::Pets');
    expect(files['src/client.rs']).toContain('std::env::var("PETSTORE_API_KEY")');

    const pets = files['src/pets.rs'];
    // path params positional (&str), query/body via the params struct
    expect(pets).toContain('pub async fn list(&self, params: PetsListParams) -> Result<Page<Pet>, Error>');
    expect(pets).toContain('pub async fn create(&self, params: PetsCreateParams) -> Result<Pet, Error>');
    expect(pets).toContain('pub async fn retrieve(&self, pet_id: &str) -> Result<Pet, Error>');
    // required string path param is guarded
    expect(pets).toContain('return Err(Error::InvalidArgument("pet_id".to_string()));');
    // cursor list wraps the response in a Page
    expect(pets).toContain('Page::from_value(value, "data", Some("has_more"))');
    // binary download returns raw bytes
    expect(pets).toContain('pub async fn download_photo(&self, pet_id: &str) -> Result<Vec<u8>, Error>');
    expect(pets).toContain('req.send_bytes().await');
  });

  it('emits serde structs and a string enum with a forward-compat catch-all', () => {
    const models = opensdkRust(readIR('1.basic'))['src/models.rs'];
    expect(models).toContain('pub struct Pet');
    expect(models).toContain('#[serde(default, skip_serializing_if = "Option::is_none")]');
    expect(models).toContain('pub enum PetStatus');
    expect(models).toContain('#[serde(rename = "available")]');
    expect(models).toContain('#[serde(other)]');
  });

  it('bakes the sdk-behavior policy into the reqwest transport', () => {
    const transport = opensdkRust(readIR('1.basic'))['src/transport.rs'];
    expect(transport).toContain('pub const DEFAULT_BASE_URL: &str = "https://api.petstore.io/v1";');
    expect(transport).toContain('pub const USER_AGENT: &str = "petstore-rust/1.2.0";');
    expect(transport).toContain('pub const MAX_RETRIES: u32 = 2;');
    expect(transport).toContain('pub const RETRYABLE_STATUS: &[u16] = &[408, 429, 500, 502, 503, 504];');
    expect(transport).toContain('pub const REQUEST_ID_HEADER: &str = "X-Request-ID";');
    expect(transport).toContain('rb = rb.bearer_auth(api_key);');
  });

  it('routes multipart, form and idempotency injection (2.wire)', () => {
    const files = opensdkRust(readIR('2.wire'));
    const filesRs = files['src/files.rs'];
    expect(filesRs).toContain('req = req.multipart_file("file", value.clone());');
    expect(filesRs).toContain('req = req.query_csv("statuses", serde_json::to_value(value)?);');
    expect(filesRs).toContain('req = req.header_json("Idempotency-Key", serde_json::to_value(value)?);');
    const tokens = files['src/tokens.rs'];
    expect(tokens).toContain('req = req.form_json("grant_type", serde_json::to_value(value)?);');
    expect(tokens).toContain('req = req.idempotency();');
  });

  it('emits a serde-tagged discriminated union and an untagged union (3.unions)', () => {
    const models = opensdkRust(readIR('3.unions'))['src/models.rs'];
    expect(models).toContain('#[serde(tag = "type")]');
    expect(models).toContain('pub enum Shape');
    expect(models).toContain('Circle(Circle),');
    expect(models).toContain('#[serde(untagged)]');
    expect(models).toContain('pub enum Payload');
  });
});
